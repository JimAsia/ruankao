/* 12_logic_shortcircuit.c —— 关系运算符、逻辑运算符、短路求值
 *
 * 怎么观察"短路"？靠 ++ 的副作用。
 * 如果右边被求值了，i 会变；没变，就说明右边根本没执行。
 */
#include <stdio.h>

int main(void)
{
    /* ---------- 关系运算符：结果是 1 或 0 ---------- */
    printf("=== 关系运算符 ===\n");
    printf("3 >  2  = %d\n", 3 >  2);
    printf("3 >= 3  = %d\n", 3 >= 3);
    printf("3 <  2  = %d\n", 3 <  2);
    printf("3 == 3  = %d     == 才是「等于」\n", 3 == 3);
    printf("3 != 2  = %d\n", 3 != 2);

    /* ---------- 真假的判定规则：非 0 即真 ---------- */
    printf("\n=== C 没有专门的布尔类型：非 0 即真，0 为假 ===\n");
    printf("!5   = %d    5 是真，取非得 0\n", !5);
    printf("!0   = %d    0 是假，取非得 1\n", !0);
    printf("!(-1)= %d    -1 也是真\n", !(-1));
    printf("!0.5 = %d    0.5 也是真\n", !0.5);

    /* ---------- 逻辑与：两边都真才真 ---------- */
    printf("\n=== 逻辑与 && ===\n");
    printf("1 && 1 = %d\n", 1 && 1);
    printf("1 && 0 = %d\n", 1 && 0);
    printf("0 && 1 = %d\n", 0 && 1);

    /* ---------- 逻辑或：一边真就真 ---------- */
    printf("\n=== 逻辑或 || ===\n");
    printf("1 || 0 = %d\n", 1 || 0);
    printf("0 || 0 = %d\n", 0 || 0);

    /* ---------- 短路求值：用 ++ 观察右边到底执行了没有 ---------- */
    printf("\n=== 短路求值（重点）===\n");

    int i = 0;
    int r1 = (0 && ++i);
    printf("i = 0,  r = (0 && ++i)\n");
    printf("  r = %d, i = %d\n", r1, i);
    printf("  → i 没变，说明 && 左边已经为假，右边 ++i 压根没执行\n");

    i = 0;
    int r2 = (1 || ++i);
    printf("\ni = 0,  r = (1 || ++i)\n");
    printf("  r = %d, i = %d\n", r2, i);
    printf("  → i 没变，说明 || 左边已经为真，右边 ++i 也没执行\n");

    i = 0;
    int r3 = (1 && ++i);
    printf("\ni = 0,  r = (1 && ++i)\n");
    printf("  r = %d, i = %d\n", r3, i);
    printf("  → i 变了，说明左边为真时，右边必须求值才能定结果\n");

    i = 0;
    int r4 = (0 || ++i);
    printf("\ni = 0,  r = (0 || ++i)\n");
    printf("  r = %d, i = %d\n", r4, i);
    printf("  → 左边为假，右边必须求值\n");

    /* ---------- 短路有什么用：把危险操作放在后面 ---------- */
    printf("\n=== 短路的实际意义 ===\n");
    printf("写法  p != 0 && 10 / p > 2\n");
    printf("如果 p 是 0，左边为假，右边 10/p 不执行，不会除零崩溃\n");
    printf("这就是「把可能出事的操作放右边」的价值\n");

    return 0;
}
