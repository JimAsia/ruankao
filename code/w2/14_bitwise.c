/* 14_bitwise.c —— 位运算：& | ^ ~ << >>
 *
 * 位运算直接操作二进制位，只对整数有效（float 不行）。
 * 软考喜欢考：按位与、按位或、异或、左移右移的结果。
 8 14 6
 */
#include <stdio.h>

int main(void)
{
    unsigned int a = 12;    /* 二进制 1100 */
    unsigned int b = 10;    /* 二进制 1010 */

    printf("a = %u    二进制 1100\n", a);
    printf("b = %u    二进制 1010\n", b);

    /* ---------- 四种基本位运算 ---------- */
    printf("\n=== 逐位对照 ===\n");
    printf("        1100\n");
    printf("      & 1010\n");
    printf("      ------\n");
    printf("        1000 = %u    按位与：两位都是 1 才得 1\n", a & b);

    printf("\n        1100\n");
    printf("      | 1010\n");
    printf("      ------\n");
    printf("        1110 = %u    按位或：有一位是 1 就得 1\n", a | b);

    printf("\n        1100\n");
    printf("      ^ 1010\n");
    printf("      ------\n");
    printf("        0110 = %u     按位异或：两位不同才得 1\n", a ^ b);

    /* ---------- 按位取反 ---------- */
    printf("\n=== 按位取反 ~：0 变 1，1 变 0 ===\n");
    printf("~a = %u\n", ~a);
    printf("  12 的 32 位是 000...0001100\n");
    printf("  取反后是     111...1110011，按无符号读就是 %u\n", ~a);
    printf("  所以 ~a 恰好等于 4294967295 - 12 = %u\n", 4294967295u - 12u);

    /* ---------- 移位 ---------- */
    printf("\n=== 移位：左移乘 2，右移除 2 ===\n");
    printf("1u << 4  = %u     左移 4 位 = 乘 16\n", 1u << 4);
    printf("3u << 2  = %u     左移 2 位 = 乘 4\n", 3u << 2);
    printf("32u >> 3 = %u     右移 3 位 = 除以 8 取整\n", 32u >> 3);
    printf("35u >> 3 = %u     右移是向下取整（丢掉低位）\n", 35u >> 3);

    /* ---------- 三个实用套路 ---------- */
    printf("\n=== 三个必须会的套路 ===\n");

    int n = 7;
    printf("n = %d\n", n);
    printf("n & 1        = %d    最低位是 1 → 奇数；是 0 → 偶数\n", n & 1);
    printf("n | 8        = %d    把第 3 位置 1（7 变 15）\n", n | 8);
    printf("n & ~1       = %d    把最低位清零（7 变 6，即变成偶数）\n", n & ~1);
    printf("n ^ n        = %d    任何数异或自己都是 0\n", n ^ n);
    printf("n ^ 0        = %d    任何数异或 0 都是自己\n", n ^ 0);

    /* ---------- 移位的一个大坑 ---------- */
    printf("\n=== 坑：移位数超过位宽是未定义行为 ===\n");
    printf("对 32 位 int 写 1 << 32，标准没说会发生什么，不同机器结果不同\n");
    printf("安全范围：移动 0 ~ 31 位\n");

	printf("\n输出什么，为什么\n");
	printf("%d\n", -1 > 1u);
	printf("\n(int)3.99 和 (int)-3.99 的结果\n");
	printf("%d\n%d\n", (int)3.99, (int)-3.99);
	
    return 0;
}
