/* 13_incdec.c —— 自增自减：++i 与 i++ 到底差在哪
 *
 * 一句话：++i 是「先加再取值」，i++ 是「先取值再加」。
 * 单独成句时两者完全等价，混进表达式里才会出事。
 */
#include <stdio.h>

int main(void)
{
    int i;

    /* ---------- 前置：先加，再取值 ---------- */
    printf("=== 前置 ++i ===\n");
    i = 5;
    printf("初始 i = %d\n", i);
    printf("++i 这个表达式的值 = %d\n", ++i);
    printf("执行后 i         = %d\n", i);

    /* ---------- 后置：先取值，再加 ---------- */
    printf("\n=== 后置 i++ ===\n");
    i = 5;
    printf("初始 i = %d\n", i);
    printf("i++ 这个表达式的值 = %d\n", i++);
    printf("执行后 i         = %d\n", i);

    /* ---------- 单独成句：没区别 ---------- */
    printf("\n=== 单独写成一句时，两者完全等价 ===\n");
    i = 5;
    i++;
    printf("i = 5; i++;   → i = %d\n", i);
    i = 5;
    ++i;
    printf("i = 5; ++i;   → i = %d\n", i);

    /* ---------- 混进表达式：区别就出来了 ---------- */
    printf("\n=== 混进表达式，区别才要命 ===\n");
    i = 5;
    int a = i++ + 10;
    printf("i = 5, a = i++ + 10  →  a = %d, i = %d\n", a, i);
    printf("  先拿 5 参与加法得 15，然后 i 才变 6\n");

    i = 5;
    int b = ++i + 10;
    printf("i = 5, b = ++i + 10  →  b = %d, i = %d\n", b, i);
    printf("  先把 i 加到 6，再拿 6 参与加法得 16\n");

    /* ---------- 自减同理 ---------- */
    printf("\n=== 自减完全同理 ===\n");
    i = 5;
    int c = i--;
    printf("c = i--  →  c = %d, i = %d     先取 5，再变 4\n", c, i);

    i = 5;
    int d = --i;
    printf("d = --i  →  d = %d, i = %d     先变 4，再取 4\n", d, i);

    /* ---------- 绝对不要写的两种东西 ---------- */
    printf("\n=== 红线：同一表达式里对同一变量多次副作用 ===\n");
    printf("  i + i++      未定义行为\n");
    printf("  i++ + ++i    未定义行为\n");
    printf("  a[i] = i++   未定义行为\n");
    printf("这类代码不同编译器给出不同结果，软考不会考这种题，\n");
    printf("因为标准根本没规定答案。考试只考「i++ 与 ++i 各自的值」这种有确定答案的。\n");

    return 0;
}
