/* 15_precedence.c —— 运算符优先级与结合性
 *
 * ⚠️ 本文件故意保留 2 处 -Wparentheses 警告。
 *    因为这两行正是在演示「优先级可能不是你以为的那样」，
 *    编译器看到 x & y == 0 同样觉得可疑并出言提醒 —— 这正是警告的价值。
 *    真实业务代码里遇到这个警告，正确做法是加括号消除它。
 *
 * 优先级决定「谁先算」，结合性决定「同级从左还是从右」。
 * 记不住全表没关系，记住三条铁律 + 多用括号。
 */
#include <stdio.h>

int main(void)
{
    /* ---------- 铁律一：括号永远最高 ---------- */
    printf("=== 括号最高 ===\n");
    printf("1 + 2 * 3     = %d\n", 1 + 2 * 3);
    printf("(1 + 2) * 3   = %d\n", (1 + 2) * 3);

    /* ---------- 铁律二：算术 > 关系 > 逻辑 > 赋值 ---------- */
    printf("\n=== 优先级从高到低：算术 > 关系 > 逻辑 > 赋值 ===\n");
    printf("3 > 2 + 1     = %d     先算 2+1 得 3，再比 3>3\n", 3 > 2 + 1);
    printf("1 + 1 == 2    = %d     先算加法，再判断相等\n", 1 + 1 == 2);
    printf("1 || 0 && 0   = %d     && 高于 ||，等价于 1 || (0&&0)\n", 1 || 0 && 0);

    /* ---------- 铁律三：赋值最低，且从右往左 ---------- */
    printf("\n=== 赋值优先级最低，结合性从右到左 ===\n");
    int a, b, c;
    a = b = c = 5;
    printf("a = b = c = 5  →  a=%d b=%d c=%d\n", a, b, c);
    printf("  先算 c=5，再算 b=c，最后算 a=b\n");

    /* ---------- 同级运算符：看结合性 ---------- */
    printf("\n=== 同级：算术左结合，赋值右结合 ===\n");
    printf("10 - 3 - 2    = %d    等价于 (10-3)-2，不是 10-(3-2)\n", 10 - 3 - 2);
    printf("100 / 10 / 2  = %d   等价于 (100/10)/2\n", 100 / 10 / 2);
    printf("2 * 3 %% 4     = %d    乘和取余同级，从左到右\n", 2 * 3 % 4);

    /* ---------- 最容易错的一处：位运算优先级低于关系运算 ---------- */
    printf("\n=== 大坑：位运算 & | ^ 的优先级低于 == 和 < ===\n");
    int x = 2;      /* 10 */
    int y = 5;      /* 101 */
    printf("x = %d, y = %d,  x & y = %d\n", x, y, x & y);
    printf("x & y == 0     = %d\n", x & y == 0);
    printf("  实际被理解成  x & (y == 0)  →  %d & 0  = 0\n", x);
    printf("(x & y) == 0   = %d\n", (x & y) == 0);
    printf("  加了括号才是我们想表达的\n");

    /* ---------- 经典笔误：= 写成 == ---------- */
    printf("\n=== 经典笔误：= 与 == ===\n");
    int n = 3;
    printf("n == 3  →  %d     这是判断，结果是 1\n", n == 3);
    printf("n = 4   这个表达式的值是 %d，而且把 n 改成了 4\n", (n = 4));
    printf("所以 if (n = 0) 永远是假，if (n = 1) 永远是真 —— 编译器不报错，逻辑全错\n");

    /* ---------- 记不住怎么办 ---------- */
    printf("\n=== 实战建议 ===\n");
    printf("记不住优先级不会影响写对代码，反复加括号就完事：\n");
    printf("  (a & b) == 0        比  a & b == 0   清楚一万倍\n");
    printf("  ((x > 0) && (y > 0))  虽然啰嗦但绝不出错\n");
    printf("考试时再按优先级表算，平时写代码一律加括号。\n");

    return 0;
}
