/* ex14 参考答案 —— 用括号说清意图
 *
 * 结论对照：
 *   ⓐ 3 > 2 + 1 = 0      3 > (2+1) = 0        加括号不改变结果（加法本来就先算）
 *   ⓑ 1 || 0 && 0 = 1    (1||0) && 0 = 0      **改变了！** && 默认高于 ||
 *   ⓒ 2 & 5 == 0 = 0     (2&5) == 0 = 1       **改变了！** == 默认高于 &
 *   ⓓ 10-3-2 = 5         10-(3-2) = 9         **改变了！** 减法左结合
 *   ⓔ 1+2*3 = 7          (1+2)*3 = 9          **改变了！** 乘法默认高于加法
 *
 * 这五组里，ⓑ 和 ⓒ 是最容易记错的。
 */
#include <stdio.h>

int main(void)
{
    printf("ⓐ 3 > 2 + 1      = %d\n", 3 > 2 + 1);
    printf("ⓐ 3 > (2 + 1)    = %d\n", 3 > (2 + 1));

    printf("ⓑ 1 || 0 && 0    = %d\n", 1 || 0 && 0);
    printf("ⓑ (1 || 0) && 0  = %d\n", (1 || 0) && 0);

    printf("ⓒ 2 & 5 == 0     = %d\n", 2 & 5 == 0);
    printf("ⓒ (2 & 5) == 0   = %d\n", (2 & 5) == 0);

    printf("ⓓ 10 - 3 - 2     = %d\n", 10 - 3 - 2);
    printf("ⓓ 10 - (3 - 2)   = %d\n", 10 - (3 - 2));

    printf("ⓔ 1 + 2 * 3      = %d\n", 1 + 2 * 3);
    printf("ⓔ (1 + 2) * 3    = %d\n", (1 + 2) * 3);

    return 0;
}
