/* ex12 —— 预测短路求值的结果
 *
 * 这是本练习的核心：先【人工预测】每组的 r 和 i，写下来，
 * 再运行程序对答案。预测对了才算真懂。
 *
 * 预测表（先填这里，再跑）：
 *   ① 0 && ++i   →  r = ___ , i = ___
 *   ② 1 || ++i   →  r = ___ , i = ___
 *   ③ 1 && ++i   →  r = ___ , i = ___
 *   ④ 0 || ++i   →  r = ___ , i = ___
 *
 * 要求：把下面四组的 TODO 补完（每组都要先把 i 重置为 0）
 */
#include <stdio.h>

int main(void)
{
    int i;
    int r;

    /* ① */
    i = 0;
    r = 0 && ++i;          /* TODO: 如果这行不对，改成你认为正确的表达式 0 , 0*/
    printf("① r = %d, i = %d\n", r, i);

    /* ② */
    i = 0;
    r = 1 || ++i;                 /* TODO: 补上正确的表达式 1, 0*/
    printf("② r = %d, i = %d\n", r, i);

    /* ③ */
    i = 0;
    r = 1 && ++i;                 /* TODO 1, 1*/
    printf("③ r = %d, i = %d\n", r, i);

    /* ④ */
    i = 0;
    r = 0 || ++i;                 /* TODO 1, 1*/
    printf("④ r = %d, i = %d\n", r, i);

    return 0;
}
