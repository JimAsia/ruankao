/* 31_for.c —— for 循环的全部形态
 *
 * for (初始化; 条件; 更新) { 循环体 }
 * 执行顺序：初始化 → 判断 → 体 → 更新 → 判断 → 体 → ...
 */
#include <stdio.h>

int main(void)
{
    /* ---------- ① 最标准的形式 ---------- */
    printf("=== ① 标准 for ===\n");
    for (int i = 0; i < 5; i++) {
        printf("i = %d  ", i);
    }
    printf("\n");
    /* 注意：i 从 0 到 4，共 5 次。
     * "i < 5" 决定了执行 5 次，最后一次进入时 i = 4。 */

    /* ---------- ② 从 1 数到 n（更符合人的直觉） ---------- */
    printf("\n=== ② 从 1 数到 5 ===\n");
    for (int i = 1; i <= 5; i++) {
        printf("i = %d  ", i);
    }
    printf("\n");

    /* ---------- ③ 倒序 ---------- */
    printf("\n=== ③ 倒序 ===\n");
    for (int i = 5; i >= 1; i--) {
        printf("i = %d  ", i);
    }
    printf("\n");

    /* ---------- ④ 步长不为 1 ---------- */
    printf("\n=== ④ 步长为 2（只打印偶数）===\n");
    for (int i = 0; i <= 10; i += 2) {
        printf("%d ", i);
    }
    printf("\n");

    /* ---------- ⑤ 步长翻倍：共 log2(n) 次 ---------- */
    printf("\n=== ⑤ 每次乘 2 ===\n");
    for (int i = 1; i <= 100; i *= 2) {
        printf("%d ", i);
    }
    printf("\n");
    printf("  循环体只执行了 7 次（i = 1,2,4,8,16,32,64），第 8 次判断 i=128 时退出\n");
    printf("  这就是 O(log n)：n 翻倍增长时，轮数只按对数增加\n");

    /* ---------- ⑥ 三段都可以省略，但分号不能省 ---------- */
    printf("\n=== ⑥ 省略三段 ===\n");
    int i = 0;
    for (; i < 3; ) {           /* 省略初始化和更新 */
        printf("i = %d  ", i);
        i++;                    /* 更新挪进循环体 */
    }
    printf("\n");
    printf("  for (;;) 就是死循环，等价于 while (1)\n");

    /* ---------- ⑦ 循环变量可以是 char ---------- */
    printf("\n=== ⑦ 循环变量是字符 ===\n");
    for (char c = 'a'; c <= 'e'; c++) {
        printf("%c ", c);
    }
    printf("\n");
    printf("  字符本质是整数，所以能做循环变量\n");

    /* ---------- ⑧ 循环变量的作用域 ---------- */
    printf("\n=== ⑧ 作用域 ===\n");
    for (int k = 0; k < 3; k++) {
        /* k 只在这个循环内有效 */
    }
    printf("  循环结束后 k 已经不存在了，想在外面用必须在外面声明\n");

    return 0;
}
