/* ex74 参考答案 —— 递归求最大公约数 */
#include <stdio.h>

int gcd(int a, int b)
{
    if (b == 0) return a;               /* 出口 */
    return gcd(b, a % b);               /* 递推 */
}

int main(void)
{
    printf("gcd(12, 18) = %d\n", gcd(12, 18));
    printf("gcd(100, 75) = %d\n", gcd(100, 75));
    printf("gcd(17, 5) = %d\n", gcd(17, 5));
    return 0;
}

/* 这是递归最漂亮的例子：三行代码，没有循环，完全贴合数学定义。
 *
 * gcd(12, 18) 的展开：
 *   gcd(12, 18) → gcd(18, 12 % 18 = 12)
 *   gcd(18, 12) → gcd(12, 18 % 12 = 6)
 *   gcd(12, 6)  → gcd(6,  12 % 6  = 0)
 *   gcd(6, 0)   → 出口，返回 6
 *
 * 为什么 a % b 能缩小规模？
 *   因为余数一定小于除数，所以每轮的第二个参数严格变小，
 *   最终必然到 0。
 *
 * 为什么 b == 0 时答案是 a？
 *   当 gcd(x, 0) 时，x 能整除 x 和 0，所以最大公约数就是 x。
 *
 * 对比 W4 的迭代版：
 *   while (b != 0) { int t = a % b; a = b; b = t; }
 * 两者等价，但递归版一眼就能看出「这是在辗转相除」。 */
