/* ex73 参考答案 —— 递归求斐波那契 */
#include <stdio.h>

long long fib(int n)
{
    if (n <= 2) return 1;               /* 出口：前两项都是 1 */
    return fib(n - 1) + fib(n - 2);     /* 递推 */
}

int main(void)
{
    printf("fib(10) = %lld\n", fib(10));
    printf("fib(20) = %lld\n", fib(20));
    printf("fib(30) = %lld\n", fib(30));
    return 0;
}

/* ⚠️ 这个写法「正确但很慢」，必须知道为什么：
 *
 * 算 fib(5) 的展开：
 *   fib(5) = fib(4) + fib(3)
 *          = (fib(3) + fib(2)) + (fib(2) + fib(1))
 *            ↑ fib(3) 被算了两次
 *          = ((fib(2)+fib(1)) + 1) + (1 + 1)
 *            ↑ fib(2) 被算了三次 ...
 *
 * 同一批子问题被反复计算，调用次数呈指数增长：
 *   fib(10) → 109 次
 *   fib(20) → 13529 次
 *   fib(30) → 1664079 次
 *   fib(40) → 约 3 亿次
 *
 * 这就是「朴素递归」的经典缺陷。S2 会讲两种解法：
 *   ① 改迭代 —— O(n)，用两个变量滚动
 *   ② 记忆化 —— 把算过的结果存起来，避免重复
 *
 * 软考《基础知识》常问「斐波那契递归的时间复杂度」，
 * 答案是 O(2ⁿ)，不是 O(n)。 */
