/* 计算 2 的 n 次方 */
static long long pow2(int n)
{
    long long r = 1;
    for (int i = 0; i < n; i++) r *= 2;
    return r;
}

/* log2 向下取整 */
static int floorLog2(int n)
{
    int lg = 0;
    while (n > 1) { n /= 2; lg++; }
    return lg;
}

