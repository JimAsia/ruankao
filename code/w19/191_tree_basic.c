/* 191_tree_basic.c —— 树的概念与二叉树的性质
 *
 * 树是非线性的数据结构：每个节点可以有多个孩子。
 * 二叉树是「每个节点最多两个孩子」的特殊树 —— 软考主要考这个。
 *
 * 本文件用程序验证二叉树的三条核心性质（软考必考）：
 *   ① 第 i 层最多 2^(i-1) 个节点（i >= 1）
 *   ② 深度为 k 的二叉树最多 2^k - 1 个节点
 *   ③ 叶子数 n0 = 度为 2 的节点数 n2 + 1
 */

#include <stdio.h>

/* 计算 2 的 n 次方（n 较小，不会溢出） */
static long long pow2(int n)
{
    long long r = 1;
    for (int i = 0; i < n; i++) r *= 2;
    return r;
}

/* 计算第 i 层的节点数（满二叉树，从 1 开始数层） */
static long long nodesAtLevel(int i)
{
    return pow2(i - 1);
}

/* 计算深度 k 的满二叉树总节点数 */
static long long nodesInTree(int k)
{
    return pow2(k) - 1;
}

int main(void)
{
    /* ---------- ① 第 i 层最多 2^(i-1) 个 ---------- */
    printf("=== ① 性质一：第 i 层最多 2^(i-1) 个节点 ===\n");
    printf("  %-8s %-12s %s\n", "层号 i", "最多节点数", "公式");
    printf("  --------------------------------------\n");
    for (int i = 1; i <= 6; i++) {
        printf("  %-8d %-12lld 2^(%d-1)\n", i, nodesAtLevel(i), i);
    }

    printf("\n  ⭐ 为什么是 2^(i-1)？\n");
    printf("     第 1 层：1 个（根）\n");
    printf("     第 2 层：每个节点最多 2 个孩子 → 2 个\n");
    printf("     第 3 层：每个节点最多 2 个孩子 → 2*2 = 4 个\n");
    printf("     每往下一层，最多翻一倍 → 2^(i-1)\n");

    /* ---------- ② 深度 k 最多 2^k - 1 个 ---------- */
    printf("\n=== ② 性质二：深度 k 最多 2^k - 1 个节点 ===\n");
    printf("  %-8s %-14s %s\n", "深度 k", "最多节点数", "累计");
    printf("  --------------------------------------\n");
    long long running = 0;
    for (int k = 1; k <= 6; k++) {
        running += nodesAtLevel(k);
        printf("  %-8d %-14lld 1+2+4+...+2^(%d-1) = %lld\n",
               k, nodesInTree(k), k, running);
    }

    printf("\n  ⭐ 等比数列求和：1 + 2 + 4 + ... + 2^(k-1) = 2^k - 1\n");
    printf("     深度 6 的满二叉树最多 63 个节点。\n");

    /* ---------- ③ 叶子数 = 度 2 节点数 + 1 ---------- */
    printf("\n=== ③ 性质三：n0 = n2 + 1（叶子数 = 度为2的节点数 + 1）===\n");

    /* 用一个具体的树来验证。构造一棵树，统计各种度数的节点数。
     * 这里手动构造一个已知结构的树来数。 */
    printf("  构造一棵树：\n");
    printf("        A\n");
    printf("       / \\\n");
    printf("      B   C\n");
    printf("     / \\   \\\n");
    printf("    D   E   F\n");
    printf("           / \\\n");
    printf("          G   H\n");

    /* 统计：度为 2 的节点 = A(有B,C)、C(有F)、F(有G,H) = 3 个
     *       叶子 = D、E、G、H = 4 个
     *       度为 1 的节点 = B(只有D,E? 不，B有两个孩子)
     *       重新算：A(2孩子)、B(2孩子D,E)、C(1孩子F)、F(2孩子G,H)
     *       度为2：A、B、F = 3 个
     *       度为1：C = 1 个
     *       叶子：D、E、G、H = 4 个
     *       验证：n0 = 4 = n2 + 1 = 3 + 1 ✓ */

    int n2 = 3, n0 = 4;
    printf("\n  统计：度为 2 的节点 = A、B、F = %d 个\n", n2);
    printf("        叶子节点 = D、E、G、H = %d 个\n", n0);
    printf("        验证：n0 = %d = n2 + 1 = %d + 1 ✓\n", n0, n2);

    printf("\n  ⭐ 这个性质怎么推出来？\n");
    printf("     设总节点数 n，度为 2 的节点数 n2，度为 1 的 n1，叶子 n0。\n");
    printf("     （1）节点总数：n = n0 + n1 + n2\n");
    printf("     （2）边数 = n - 1（树有 n 个节点就有 n-1 条边）\n");
    printf("     （3）边数也 = n1 + 2*n2（度 1 贡献 1 条边，度 2 贡献 2 条）\n");
    printf("     联立：n0 + n1 + n2 - 1 = n1 + 2*n2\n");
    printf("           n0 = n2 + 1\n");

    printf("\n  📌 这条性质软考选择题几乎每年都考，要会推导。\n");
    printf("     变体：已知 n2 求 n0，或已知 n0 求 n2。\n");

    /* ---------- ④ 满二叉树 vs 完全二叉树 ---------- */
    printf("\n=== ④ 满二叉树 vs 完全二叉树 ===\n");
    printf("  满二叉树：每一层都填满。深度 k 有 2^k-1 个节点。\n");
    printf("  完全二叉树：除了最后一层，其他层都填满，最后一层从左到右连续。\n");
    printf("\n  %-14s %s\n", "例子（深度3）", "说明");
    printf("  --------------------------------------------------\n");
    printf("  满二叉树：    A            每一层都满\n");
    printf("              / \\\n");
    printf("             B   C\n");
    printf("            / \\ / \\\n");
    printf("           D  E F  G\n");
    printf("\n  完全二叉树：  A            最后一层从左到右，缺 G\n");
    printf("              / \\\n");
    printf("             B   C\n");
    printf("            / \\ /\n");
    printf("           D  E F\n");
    printf("\n  不是完全二叉树：A            最后一层有空洞（F 空但 G 有）\n");
    printf("              / \\\n");
    printf("             B   C\n");
    printf("            / \\   \\\n");
    printf("           D  E   G\n");

    printf("\n  ⭐ 关键区分：\n");
    printf("     满二叉树：每层都满\n");
    printf("     完全二叉树：只有最后一层可以不满，且必须从左到右连续\n");
    printf("     完全二叉树不一定是满二叉树，满二叉树一定是完全二叉树\n");

    /* ---------- ⑤ 完全二叉树的性质（重点） ---------- */
    printf("\n=== ⑤ 完全二叉树的两个性质（软考高频）===\n");
    printf("  性质 A：完全二叉树深度 = ⌊log2(n)⌋ + 1\n");
    printf("          （n 个节点，向下取整 log）\n");
    printf("\n  性质 B：编号从 1 开始，第 i 个节点：\n");
    printf("          左孩子 = 2i\n");
    printf("          右孩子 = 2i + 1\n");
    printf("          父节点 = ⌊i/2⌋\n");
    printf("          叶子条件 = i > n/2\n");

    /* 验证深度公式 */
    printf("\n  验证深度公式：\n");
    printf("  %-10s %-14s %s\n", "节点数 n", "深度", "⌊log2(n)⌋+1");
    printf("  --------------------------------------\n");
    int ns[] = {1, 2, 3, 4, 7, 8, 15, 16};
    for (int t = 0; t < 8; t++) {
        int n = ns[t];
        /* 算 log2 向下取整 */
        int lg = 0, x = n;
        while (x > 1) { x /= 2; lg++; }
        printf("  %-10d %-14d %d\n", n, lg + 1, lg + 1);
    }

    printf("\n  ⭐ 8 个节点的完全二叉树深度是 4，15 个是 4，16 个是 5。\n");
    printf("     注意边界：n 是 2 的幂时会「跳层」。\n");

    /* ---------- ⑥ 孩子下标规律 ---------- */
    printf("\n=== ⑥ 编号规律验证（i 从 1 起）===\n");
    printf("  %-6s %-10s %-10s %s\n", "节点 i", "左孩子 2i", "右孩子 2i+1", "父节点 i/2");
    printf("  --------------------------------------------------\n");
    for (int i = 1; i <= 6; i++) {
        printf("  %-6d %-10d %-10d %d\n", i, 2 * i, 2 * i + 1, i / 2);
    }

    printf("\n  ⭐ 这个规律是「堆」和「二叉树的顺序存储」的基础。\n");
    printf("     W20 讲堆排序时还要用到。\n");

    return 0;
}
