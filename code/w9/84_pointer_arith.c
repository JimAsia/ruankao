/* 84_pointer_arith.c —— 指针运算
 *
 * ⚠️ 本文件故意保留 1 处 -Wunused-value 警告。
 *    第 ⑦ 段的 `*r++;` 取了值又丢弃（只为演示「指针后移、值不变」），
 *    编译器提醒「你算出来的值没用上」—— 这正好说明这种写法容易让人误解。
 *
 * 指针能做的运算只有四种：
 *   加减整数、指针相减、自增自减、比较
 * 指针不能乘除，也不能加两个指针。
 */

#include <stdio.h>

int main(void)
{
    int a[6] = {10, 20, 30, 40, 50, 60};

    /* ---------- ① 加减整数：以元素为单位 ---------- */
    printf("=== ① 指针加减整数 ===\n");
    int *p = a;                 /* 指向 a[0] */

    for (int i = 0; i < 6; i++) {
        printf("  p + %d → 值 %-3d 地址 %p\n", i, *(p + i), (void *)(p + i));
    }
    printf("  每加 1，地址增加 %zu 字节（= sizeof(int)）\n", sizeof(int));

    /* ---------- ② 指针相减：得到元素个数 ---------- */
    printf("\n=== ② 指针相减 = 相隔几个元素 ===\n");
    int *first = &a[0];
    int *last  = &a[5];

    printf("  last - first = %td   （相隔几个元素，不是字节数）\n", last - first);
    printf("  如果按字节算：%ld 字节\n", (long)((char *)last - (char *)first));
    printf("  ⚠️ 两个指针相减得到的是【元素个数】，这是 C 语言的规定\n");

    /* ---------- ③ 用指针相减求数组长度 ---------- */
    printf("\n=== ③ 求长度的另一种方式 ===\n");
    int len = (int)(&a[6] - &a[0]);         /* 注意：&a[6] 是越界的地址，但可以取 */
    printf("  &a[6] - &a[0] = %d（正好是数组长度）\n", len);
    printf("  这个技巧在函数内很有用，但不如 sizeof 直观\n");

    /* ---------- ④ 自增自减 ---------- */
    printf("\n=== ④ p++ 与 ++p ===\n");
    p = a;

    printf("  *p     = %d\n", *p);
    printf("  *p++   = %d   ← 先取值再移动，p 现在指向 a[1]\n", *p++);
    printf("  此时 *p = %d\n", *p);

    printf("  *++p   = %d   ← 先移动再取值（跳过 a[1] 到 a[2]）\n", *++p);
    printf("  此时 *p = %d\n", *p);

    printf("  ⚠️ *p++ 等价于 *(p++)，不是 (*p)++\n");
    printf("     前者：取当前值，然后指针后移\n");
    printf("     后者：把指向的值加 1，指针不动\n");

    /* ---------- ⑤ 指针比较 ---------- */
    printf("\n=== ⑤ 指针可以比较 ===\n");
    int *q = &a[4];                     /* q 指向 a[4] */
    printf("  此时 p 指向 a[%d]，q 指向 a[4]\n", (int)(p - a));
    if (p < q) {
        printf("  p < q 成立 —— 因为 a[%d] 在 a[4] 前面\n", (int)(p - a));
    }
    printf("  常用在循环条件里：for (p = a; p < a + n; p++)\n");

    /* ---------- ⑥ 不能做的运算 ---------- */
    printf("\n=== ⑥ 指针不能做的运算 ===\n");
    printf("  ❌ p + q      两个指针相加，无意义\n");
    printf("  ❌ p * 2      指针不能乘\n");
    printf("  ❌ p / 2      指针不能除\n");
    printf("  ❌ p + q 即使编译过了，结果也没有意义\n");
    printf("  ✅ p + 整数、p - 整数、p - q、p++、p < q  这些都可以\n");

    /* ---------- ⑦ 经典陷阱：p++ 与 (*p)++ ---------- */
    printf("\n=== ⑦ 一个必须分清的对比 ===\n");
    int b[3] = {1, 1, 1};
    int *r = b;

    (*r)++;                 /* 值加 1，指针不动 */
    printf("  (*r)++ 之后：b[0] = %d，r 指向 b[%d]\n", b[0], (int)(r - b));

    *r++;                   /* 取值（丢弃），指针后移 */
    printf("  *r++   之后：b[0] = %d，r 指向 b[%d]\n", b[0], (int)(r - b));
    printf("  ↑ 第二种写法里 b[0] 没变，只是指针走了\n");

    return 0;
}
