/* ex81 参考答案 —— 用指针交换两个数
 *
 * ⭐ 这就是 W7 那个「swap 交换不了」的解决方案。
 */
#include <stdio.h>

void swap(int *a, int *b)
{
    int t = *a;         /* 把 a 指向的值存起来 */
    *a = *b;            /* 把 b 指向的值写到 a 指向的位置 */
    *b = t;             /* 把存下来的值写到 b 指向的位置 */
}

int main(void)
{
    int a = 0, b = 0;

    printf("请输入两个整数: ");
    if (scanf("%d %d", &a, &b) != 2) return 1;

    printf("交换前 a = %d, b = %d\n", a, b);
    swap(&a, &b);                    /* ⚠️ 传地址 */
    printf("交换后 a = %d, b = %d\n", a, b);

    return 0;
}

/* 为什么这次成功了？
 *
 * W7 的错误版本：
 *   void swapWrong(int x, int y)
 *   传的是值的副本，函数内交换副本，原件没动。
 *
 * 这个版本：
 *   void swap(int *a, int *b)
 *   传的是 a 和 b 的地址（地址也是"值"，仍然被拷贝了一份）
 *   但函数拿着地址，就能【顺着地址找到原件】并修改它。
 *
 * ⭐ 关键洞察：
 *   C 语言只有值传递，这一点没变。
 *   变的是「传什么值」—— 传值只能读，传地址能改。
 *
 * 写法提醒：
 *   如果写成 *a = *a + *b; *b = *a - *b; *a = *a - *b; 也行，
 *   但有溢出风险。用临时变量最稳。
 *   另外 (*a)++ 这种要加括号 —— *a++ 是 *(a++)，移动的是指针。 */
