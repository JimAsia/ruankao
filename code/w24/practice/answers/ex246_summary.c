/* ex246_summary.c —— 参考答案 */

#include <stdio.h>

int main(void)
{
    printf("=== 排序综合小测 ===\n\n");

    /* 题 1 */
    printf("题 1：n=1000 的快排，最坏比较次数是多少量级？\n");
    printf("  答：n(n-1)/2 = 1000×999/2 = 499500 次，即 O(n^2)\n");
    printf("  场景：数据已有序 + 取首/尾元素为基准。\n\n");

    /* 题 2 */
    printf("题 2：8 个元素做归并排序，需要几层递归？\n");
    printf("  答：log2(8) = 3 层\n");
    printf("  8 → 4 → 2 → 1，每层一分为二，3 次到底。\n\n");

    /* 题 3 */
    printf("题 3：哪个排序的「一趟」能确定一个元素的最终位置？\n");
    printf("  答：快速排序（基准归位）、选择排序（最小值归位）、\n");
    printf("      冒泡排序（最大值归位）、堆排序（堆顶归位）\n");
    printf("  ⚠️ 插入排序和归并排序【不能】—— 元素还可能被后面的插入挤动。\n\n");

    /* 题 4 */
    printf("题 4：稳定的排序有哪些？\n");
    printf("  答：插入、冒泡、归并、基数\n");
    printf("  不稳定：选择、希尔、快速、堆\n");
    printf("  ⭐ 口诀：插冒归基稳，选希快堆晃。\n\n");

    /* 题 5 */
    printf("题 5：空间 O(1) 的 O(n log n) 排序是哪个？\n");
    printf("  答：堆排序\n");
    printf("  对比：快排 O(log n)（递归栈），归并 O(n)（辅助数组）。\n\n");

    /* 题 6 */
    printf("题 6：冒泡、插入、选择，哪个比较次数与数据无关？\n");
    printf("  答：选择排序，恒为 n(n-1)/2\n");
    printf("  因为不管数据怎样，都要扫完才知道最小值在哪。\n\n");

    /* 题 7 */
    printf("题 7：基数排序是不是比较排序？复杂度？\n");
    printf("  答：不是比较排序；复杂度 O(d(n+r))\n");
    printf("  d = 位数，r = 基数。d 是常数时是线性的。\n");
    printf("  ⭐ 它能突破 O(n log n) 下界，正是因为不走「比较」这条路。\n\n");

    /* 题 8 */
    printf("题 8：给「第一趟后」的结果，怎么判断是哪种排序？\n");
    printf("  看这趟「确定了什么」：\n");
    printf("    %-14s %s\n", "现象", "对应排序");
    printf("    ----------------------------------------------\n");
    printf("    %-14s %s\n", "最大值到了末尾", "冒泡");
    printf("    %-14s %s\n", "最小值到了最前", "选择");
    printf("    %-14s %s\n", "某个元素左边全小右边全大", "快速");
    printf("    %-14s %s\n", "前 i 个局部有序", "插入");
    printf("    %-14s %s\n", "整体更接近有序但没确定位置", "希尔");

    printf("\n=== 八条必背结论 ===\n");
    printf("  1. 快排最坏 O(n^2)：已有序 + 取端点为基准\n");
    printf("  2. 归并递归层数 = log2(n)\n");
    printf("  3. 一趟能定位：快排/选择/冒泡/堆排\n");
    printf("  4. 稳定：插入、冒泡、归并、基数\n");
    printf("  5. 空间 O(1) 的 O(n log n)：堆排序\n");
    printf("  6. 选择排序比较次数与数据无关\n");
    printf("  7. 基数排序不是比较排序，O(d(n+r))\n");
    printf("  8. 链表排序用归并（空间还能是 O(1)）\n");

    printf("\n=== 总表（考前必看）===\n");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "排序", "最好", "最坏", "空间", "稳定性", "一趟后");
    printf("  ----------------------------------------------------------------------------------\n");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "直接插入", "O(n)", "O(n^2)", "O(1)", "稳定", "前 i 个有序");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "冒泡", "O(n)", "O(n^2)", "O(1)", "稳定", "最大到末尾");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "选择", "O(n^2)", "O(n^2)", "O(1)", "不稳定", "最小到最前");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "希尔", "O(n^1.3)", "O(n^1.3)", "O(1)", "不稳定", "更接近有序");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "快速", "O(nlogn)", "O(n^2)", "O(logn)", "不稳定", "基准归位");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "归并", "O(nlogn)", "O(nlogn)", "O(n)", "稳定", "局部有序");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "堆", "O(nlogn)", "O(nlogn)", "O(1)", "不稳定", "堆顶归位");
    printf("  %-10s %-12s %-12s %-12s %-10s %s\n",
           "基数", "O(d(n+r))", "O(d(n+r))", "O(n+r)", "稳定", "按位有序");

    return 0;
}
