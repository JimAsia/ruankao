/* ex245_sort_choice.c —— 参考答案 */

#include <stdio.h>

int main(void)
{
    const char *a1 = "直接插入排序";
    const char *a2 = "直接插入排序";
    const char *a3 = "归并排序";
    const char *a4 = "堆排序";
    const char *a5 = "快速排序";
    const char *a6 = "归并排序";
    const char *a7 = "基数排序";
    const char *a8 = "快速选择（快排分区思想）";

    printf("=== 场景 → 算法 ===\n");
    printf("  1. n=20 小数组         → %s\n", a1);
    printf("  2. 基本有序            → %s\n", a2);
    printf("  3. 要求稳定 n=100000   → %s\n", a3);
    printf("  4. 内存紧张            → %s\n", a4);
    printf("  5. 一般情况最快        → %s\n", a5);
    printf("  6. 链表排序            → %s\n", a6);
    printf("  7. 0~999 的整数        → %s\n", a7);
    printf("  8. 第 k 小             → %s\n", a8);

    printf("\n=== 逐题解析 ===\n");

    printf("\n场景 1：n=20 小数组 → 直接插入排序\n");
    printf("  n 小时 O(n^2) 和 O(n log n) 差别微不足道（400 vs 86 次操作），\n");
    printf("  此时「代码简单、常数小、不递归」更重要。\n");
    printf("  ⭐ 很多标准库的排序在 n < 10 时会切换成插入排序。\n");

    printf("\n场景 2：基本有序 → 直接插入排序\n");
    printf("  插入排序最好情况 O(n)，几乎有序时接近 O(n)。\n");
    printf("  冒泡也可以，但每趟仍要扫一遍，常数更大。\n");
    printf("  ⚠️ 快排在这里最差！每次选首元素当基准会退化 O(n^2)。\n");

    printf("\n场景 3：要求稳定 → 归并排序\n");
    printf("  %-10s %-12s %s\n", "候选", "稳定", "说明");
    printf("  --------------------------------------------\n");
    printf("  %-10s %-12s %s\n", "归并", "稳定 ✓", "O(n log n)，但 O(n) 空间");
    printf("  %-10s %-12s %s\n", "插入", "稳定", "O(n^2)，n 大时太慢");
    printf("  %-10s %-12s %s\n", "快排", "不稳定", "不满足要求");
    printf("  %-10s %-12s %s\n", "堆排", "不稳定", "不满足要求");
    printf("  ⭐ n=100000 要求稳定 → 只能归并（或基数）。\n");

    printf("\n场景 4：内存紧张 → 堆排序\n");
    printf("  %-10s %-12s %s\n", "排序", "空间", "说明");
    printf("  --------------------------------------------\n");
    printf("  %-10s %-12s %s\n", "堆排", "O(1) ✓", "O(n log n) 且原地");
    printf("  %-10s %-12s %s\n", "归并", "O(n)", "空间太大");
    printf("  %-10s %-12s %s\n", "快排", "O(log n)", "接近但不如堆排");
    printf("  %-10s %-12s %s\n", "插入/冒泡/选择", "O(1)", "但 O(n^2) 太慢");
    printf("  ⭐ 唯一同时满足「O(n log n) + O(1) 空间」的就是堆排序。\n");

    printf("\n场景 5：一般情况最快 → 快速排序\n");
    printf("  常数因子最小、缓存友好（原地交换、顺序访问）。\n");
    printf("  实际测试普遍比归并和堆排快 1.5~2 倍。\n");
    printf("  ⭐ 所以标准库的 sort 基本都是快排的变体（如 introsort）。\n");

    printf("\n场景 6：链表排序 → 归并排序\n");
    printf("  快排不行：链表没法随机访问，分区要找中间、要随机访问元素。\n");
    printf("  归并最合适：\n");
    printf("    - 找中点用快慢指针 O(n)\n");
    printf("    - 合并两个有序链表只用改指针，【不需要额外空间】\n");
    printf("  ⭐ 所以链表的归并排序空间是 O(1)，不是 O(n)！\n");
    printf("  📌 这是软考选择题的原题。\n");

    printf("\n场景 7：0~999 的整数 → 基数排序\n");
    printf("  位数只有 3 位，d=3，复杂度 O(3n) 线性。\n");
    printf("  也可以用计数排序（范围 0~999 直接开 1000 个桶）。\n");
    printf("  ⭐ 数据范围小且是整数 → 用「非比较排序」，能突破 O(n log n)。\n");
    printf("  ⚠️ 如果是 32 位整数随机分布，d=10，O(10n) 就未必比 O(n log n) 快了。\n");

    printf("\n场景 8：第 k 小 → 快速选择\n");
    printf("  不用完全排序。用快排分区，每次只递归一边。\n");
    printf("  平均 O(n)，最坏 O(n^2)。\n");
    printf("  ⭐ 对比：完全排序 O(n log n)，堆的方法 O(n log k)。\n");
    printf("  📌 C++ 的 nth_element 就是这个算法。\n");

    printf("\n=== 选择排序算法的四个维度 ===\n");
    printf("  1. n 的大小 —— 小用插入，大用 O(n log n)\n");
    printf("  2. 数据的初始状态 —— 基本有序用插入\n");
    printf("  3. 是否要求稳定 —— 要求就用归并\n");
    printf("  4. 空间限制 —— 紧张用堆排\n");
    printf("  ⭐ 还有一个：数据类型（整数小范围 → 基数/计数）\n");
    printf("  📌 软考选择题就考这四个维度，逐条筛即可。\n");

    return 0;
}
