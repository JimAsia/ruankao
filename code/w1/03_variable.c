/* 03_variable.c —— 变量：声明、初始化、赋值
 */
#include <stdio.h>

int main(void)
{
    /* ---------- 声明（要一块地） ---------- */
    int age;        /* 向系统申请一块能放 int 的内存，并给它起名 age。
                     * 此时里面是什么？不确定。别读。 */

    /* ---------- 赋值（往里放东西） ---------- */
    age = 18;       /* 把 18 写进 age 那块内存。注意：= 是"赋值"，不是"等于" */

    /* ---------- 声明 + 初始化（一步到位，推荐） ---------- */
    int score = 90;

    /* ---------- 一条语句声明多个同类型变量 ---------- */
    int a = 1, b = 2, c = 0;
    /* ↑ 三个都给初值。
     *   C 语言【不强制】你初始化，所以写 int c; 也合法、也能编译。
     *   但读到未初始化的局部变量会拿到垃圾值 —— 那个实验见 07_uninitialized.c */

    printf("age   = %d\n", age);
    printf("score = %d\n", score);
    printf("a = %d, b = %d, c = %d\n", a, b, c);

    /* ---------- 变量可以改 ---------- */
    score = score + 5;      /* 先算出 95，再写回 score */
    printf("score 加了 5 之后 = %d\n", score);

    score += 5;             /* 等价写法，+= 就是 "加完再存回去" */
    printf("score 再加 5 之后 = %d\n", score);

    return 0;
}
