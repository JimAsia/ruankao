/* 02_hello_explained.c —— 把第一个程序拆开看
 * 每一行都在干什么，注释就是答案。
 */
#include <stdio.h>
/* ↑ 预处理指令。把标准库头文件 stdio.h 的内容原样搬进来，
 *   相当于"借用 printf 的说明书"。
 *   stdio = standard input/output，标准输入输出。
 *   注意：这行后面没有分号。 */

int main(void)
/* ↑ 主函数。整个程序唯一的入口。
 *   int   —— 返回类型：函数结束后交回给操作系统一个整数。
 *   main  —— 名字固定，改了就找不到入口，链接会失败。
 *   void  —— 表示这个函数不接收参数。
 *   {  }  —— 函数体，大括号括起来的都是它的地盘。 */
{
    printf("Hello, Programmer!\n");
    /* ↑ printf = print formatted，格式化输出。
     *   "Hello, Programmer!\n" 是要打印的内容。
     *   \n 是转义字符"换行"，没有它，后面的东西会接在同一行。
     *   分号 ; 表示这句语句到此结束 —— C 语言的语句几乎都要分号。 */

    return 0;
    /* ↑ 返回 0 表示"程序正常结束"。
     *   返回非 0（比如 1）表示出了错。
     *   这句可以省略，但写上是对的，也是软考简答题会被问到的点。 */
}
