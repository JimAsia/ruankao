/* ex03 —— 摄氏温度转华氏温度
 * 公式：F = C × 9 / 5 + 32
 * 要求：读入一个摄氏温度（可以是小数），输出华氏温度，保留 2 位小数。
 *
 * 坑：9 / 5 如果写成整数除法，结果是 1，不是 1.8。
 *     要么写 9.0 / 5，要么写 1.8。
 *
 * 测试：输入 37     输出 98.60
 */
#include <stdio.h>

int main(void)
{
    double c;
    /* TODO */
    scanf("%lf", &c);
    double f = 0.0;
    
   
    f = c * 9.0 / 5 + 32;
    

    printf("%.2lf", f);

    return 0;
}
