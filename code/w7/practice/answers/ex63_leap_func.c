/* ex63 参考答案 —— 用函数判断闰年 */
#include <stdio.h>

int isLeap(int y)
{
    /* 能被 4 整除且不能被 100 整除，或者能被 400 整除 */
    if ((y % 4 == 0 && y % 100 != 0) || (y % 400 == 0))
        return 1;
    return 0;

    /* 更紧凑的写法（结果完全一样）：
     *   return (y % 4 == 0 && y % 100 != 0) || (y % 400 == 0);
     * 因为关系运算的结果正好就是 1 或 0，可以直接当返回值。
     * 但显式写 if/return 更易读，看个人习惯。 */
}

int main(void)
{
    printf("2000~2010 年间的闰年：\n  ");

    for (int y = 2000; y <= 2010; y++) {
        if (isLeap(y)) {
            printf("%d ", y);
        }
    }
    printf("\n");

    /* 验算：2000 是闰年（能被 400 整除），2004、2008 是（能被 4 整除且不是整百）。
     * 2010 不是。所以输出 2000 2004 2008。
     *
     * 这个函数在日历类题目里会反复用到（比如"算某年某月有多少天"），
     * 封装好以后直接调，不用每次重写判断条件。 */

    return 0;
}
